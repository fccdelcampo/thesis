import json
import os
import sys
from test_case_chooser import approve

# Ensure we can import the chooser if running from root or inside test_cases/metrics_loaders
current_dir = os.path.dirname(os.path.abspath(__file__))
project_root = os.path.abspath(os.path.join(current_dir, "../.."))
if project_root not in sys.path:
    sys.path.append(project_root)

class MetricsLoader:
    def __init__(self, sample_size=500):
        self.SAMPLE_SIZE = sample_size

    def generate_dataset(self):
        """
        Interactively approves synthetic questions generated by Gemini 
        for the metrics.
        """
        all_selected_data = []
        approved_count = 0

        print(f"\n[MetricsLoader] Starting interactive approval (Target: {self.SAMPLE_SIZE})")
        
        # Start logging to file
        os.makedirs("test_cases/logs", exist_ok=True)
        tentative_test_cases = []
        with open("/Users/franciscarlodelcampo/Documents/thesis/metrics.jsonl", "r", encoding="utf-8") as f:
            for line in f:
                try:
                    data = json.loads(line.strip())
                    tentative_test_cases.append(data)
                except json.JSONDecodeError as e:
                    print(f"[MetricsLoader] Skipping invalid JSON line {line.strip()}\nException: {e}")
        
        for index, row in enumerate(tentative_test_cases[len(tentative_test_cases)-10:]):
            print(f"\n[MetricsLoader] Evaluating item {index + 1}/{10}")
            question = row.get("question", "")
            answer = row.get("ground_truth_answer", "")
            context = row.get("context", "")
            if not (question and answer):
                continue

            try:
                with open("test_cases/logs/metrics_approval.log", "a", encoding="utf-8") as log_file:
                    log_file.write(f"Question: {question}\n")
                    log_file.flush()

                    question = f"Is this question-answer pair valid and suitable for metrics evaluation?\nQ: {question}\nA: {answer}"
                    if approve(question):
                        entry = {"question": question, "answer": answer, "context": context}
                        all_selected_data.append(entry)
                        approved_count += 1
                        
                        items_left = self.SAMPLE_SIZE - approved_count
                        print(f"   [+] APPROVED:\n    Q: {question}\n    Answer: {answer}\nCount: {approved_count}/{self.SAMPLE_SIZE}")
                        log_file.write(f"[Approved!] (Needed: {items_left}, Approved: {approved_count})\n")
                        log_file.flush()
                        print(f"   [+] Approved. Count: {approved_count}/{self.SAMPLE_SIZE}")
                    else:
                        items_left = self.SAMPLE_SIZE - approved_count
                        print(f"   [+] REJECTED:\n    Q: {question}\n    Answer: {answer}")
                        log_file.write(f"[Rejected!] (Needed: {items_left}, Approved: {approved_count})\n")
                        log_file.flush()
                        
            except Exception as e:
                print(f"[MetricsLoader] FAILED to process question: {e}")
                continue

        if approved_count < self.SAMPLE_SIZE / 2:
             print(f"\n[WARNING] MetricsLoader only approved {approved_count}/{self.SAMPLE_SIZE} items. Not enough synthetic questions generated.")

        # Save to JSONL
        output_file = "/Users/franciscarlodelcampo/Documents/thesis/test_cases/metrics.jsonl"
        with open(output_file, "a", encoding="utf-8") as f:
            for item in all_selected_data:
                f.write(json.dumps(item) + "\n")
                
        print(f"[MetricsLoader] Finished writing {len(all_selected_data)} test cases to {output_file}")
        
    def tally_tests(self):
        """
        Counts the number of test cases currently in the metrics.jsonl file.
        """
        physics_q = []
        chemistry_q = []
        biology_q = []
        all_q = {
            "physics": [],
            "biology": [], 
            "chemistry": []
        }
        approved_q = []
        approved_count = {
            "physics": {"free-form": 0, "binary": 0},
            "biology": {"free-form": 0, "binary": 0}, 
            "chemistry": {"free-form": 0, "binary": 0}
        }
        
        try:
            with open("/Users/franciscarlodelcampo/Documents/thesis/metrics.jsonl", "r", encoding="utf-8") as f:
                for line in f:
                    if line.strip():
                        try:
                            data = json.loads(line.strip())
                            all_q[data["topic"]].append(data)
                        except Exception as e:
                            continue
                        
            with open("/Users/franciscarlodelcampo/Documents/thesis/test_cases/metrics_test_cases.jsonl", "r", encoding="utf-8") as f:
                for line in f:
                    if line.strip():
                        try:
                            data = json.loads(line.strip())
                            approved_q.append(data)
                        except Exception as e:
                            continue
                        
            print(f"[MetricsLoader] Current test case count: Physics={len(physics_q)}, Chemistry={len(chemistry_q)}, Biology={len(biology_q)}")
        except FileNotFoundError:
            print("[MetricsLoader] metrics.jsonl not found. Count is 0.")
        except Exception as e:
            print(f"[MetricsLoader] Error counting test cases: {e}")
            
        new_approved_questions = []
        for approved in approved_q:
            inserted = False
            for topic, q_list in all_q.items():
                for q in q_list:
                    question = q.get("question", "")
                    if question == approved.get("question", ""):
                        approved["topic"] = topic
                        approved_count[topic]["binary" if approved["answer"].lower() in ["yes", "no"] else "free-form"] += 1
                        print(f"Approved question belongs to topic: {topic}")
                        new_approved_questions.append(approved)
                        inserted = True
                        break
            if not inserted:
                print(f"Could not determine topic for approved question: {approved.get('question', '')}")
                
        for topic, counts in approved_count.items():
            print(f"Topic: {topic} - Free-form: {counts['free-form']}, Binary: {counts['binary']}, Total Approved: {counts['free-form'] + counts['binary']}")
        
        output_file = "/Users/franciscarlodelcampo/Documents/thesis/test_cases/metrics_test_cases.jsonl"
        with open(output_file, "w", encoding="utf-8") as f:
            for item in new_approved_questions:
                f.write(json.dumps(item) + "\n")

