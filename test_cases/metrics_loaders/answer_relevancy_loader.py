import json
import os
import sys

# Ensure we can import the chooser if running from root or inside test_cases/metrics_loaders
current_dir = os.path.dirname(os.path.abspath(__file__))
project_root = os.path.abspath(os.path.join(current_dir, "../.."))
if project_root not in sys.path:
    sys.path.append(project_root)

from test_case_chooser import approve

class AnswerRelevancyLoader:
    def __init__(self, sample_size=10):
        self.SAMPLE_SIZE = sample_size

    def generate_dataset(self, dataframe):
        """
        Interactively approves synthetic questions generated by RAGAS 
        for the Answer Relevancy metric.
        """
        all_selected_data = []
        approved_count = 0

        print(f"\n[AnswerRelevancyLoader] Starting interactive approval (Target: {self.SAMPLE_SIZE})")
        
        # Start logging to file
        os.makedirs("test_cases/logs", exist_ok=True)
        
        for index, row in dataframe.iterrows():
            if approved_count >= self.SAMPLE_SIZE:
                break
                
            question = row.get("question", "")
            if not question:
                continue

            try:
                with open("test_cases/logs/answer_relevancy_approval.log", "a", encoding="utf-8") as log_file:
                    log_file.write(f"Question: {question}\n")
                    log_file.flush()

                    user_prompt = f"Approving Answer Relevancy Question:\nQ: {question}"
                    
                    if approve(user_prompt):
                        entry = {"question": question}
                        all_selected_data.append(entry)
                        approved_count += 1
                        
                        items_left = self.SAMPLE_SIZE - approved_count
                        log_file.write(f"[Approved!] (Needed: {items_left}, Approved: {approved_count})\n")
                        log_file.flush()
                        print(f"   [+] Approved. Count: {approved_count}/{self.SAMPLE_SIZE}")
                    else:
                        items_left = self.SAMPLE_SIZE - approved_count
                        log_file.write(f"[Rejected!] (Needed: {items_left}, Approved: {approved_count})\n")
                        log_file.flush()
                        
            except Exception as e:
                print(f"[AnswerRelevancyLoader] FAILED to process question: {e}")
                continue

        if approved_count < self.SAMPLE_SIZE:
             print(f"\n[WARNING] AnswerRelevancyLoader only approved {approved_count}/{self.SAMPLE_SIZE} items. Not enough synthetic questions generated.")


        # Save to JSONL
        output_file = "test_cases/answer_relevancy.jsonl"
        with open(output_file, "w", encoding="utf-8") as f:
            for item in all_selected_data:
                f.write(json.dumps(item) + "\n")
                
        print(f"[AnswerRelevancyLoader] Finished writing {len(all_selected_data)} test cases to {output_file}")
